#ifndef LKL_FSKIT_ERRNO_H
#define LKL_FSKIT_ERRNO_H

#include <errno.h>
#include <lkl/linux/errno.h>

/* LKL returns Linux errno numbers, not the host's POSIX error numbers. */
static inline int lkfs_host_errno(int error)
{
    switch (error) {
    case 0: return 0;
#define MAP_ERROR(name) case LKL_##name: return name
    MAP_ERROR(EPERM); MAP_ERROR(ENOENT); MAP_ERROR(ESRCH); MAP_ERROR(EINTR);
    MAP_ERROR(EIO); MAP_ERROR(ENXIO); MAP_ERROR(E2BIG); MAP_ERROR(ENOEXEC);
    MAP_ERROR(EBADF); MAP_ERROR(ECHILD); MAP_ERROR(EAGAIN); MAP_ERROR(ENOMEM);
    MAP_ERROR(EACCES); MAP_ERROR(EFAULT); MAP_ERROR(ENOTBLK); MAP_ERROR(EBUSY);
    MAP_ERROR(EEXIST); MAP_ERROR(EXDEV); MAP_ERROR(ENODEV); MAP_ERROR(ENOTDIR);
    MAP_ERROR(EISDIR); MAP_ERROR(EINVAL); MAP_ERROR(ENFILE); MAP_ERROR(EMFILE);
    MAP_ERROR(ENOTTY); MAP_ERROR(ETXTBSY); MAP_ERROR(EFBIG); MAP_ERROR(ENOSPC);
    MAP_ERROR(ESPIPE); MAP_ERROR(EROFS); MAP_ERROR(EMLINK); MAP_ERROR(EPIPE);
    MAP_ERROR(EDOM); MAP_ERROR(ERANGE); MAP_ERROR(EDEADLK); MAP_ERROR(ENAMETOOLONG);
    MAP_ERROR(ENOLCK); MAP_ERROR(ENOSYS); MAP_ERROR(ENOTEMPTY); MAP_ERROR(ELOOP);
    MAP_ERROR(ENOMSG); MAP_ERROR(EIDRM); MAP_ERROR(ENOSTR); MAP_ERROR(ETIME);
    MAP_ERROR(ENOSR); MAP_ERROR(EREMOTE); MAP_ERROR(ENOLINK); MAP_ERROR(EPROTO);
    MAP_ERROR(EMULTIHOP); MAP_ERROR(EBADMSG); MAP_ERROR(EOVERFLOW); MAP_ERROR(EILSEQ);
    MAP_ERROR(EUSERS); MAP_ERROR(ENOTSOCK); MAP_ERROR(EMSGSIZE); MAP_ERROR(ENOBUFS);
    MAP_ERROR(ETIMEDOUT); MAP_ERROR(ECONNREFUSED); MAP_ERROR(ESTALE); MAP_ERROR(EDQUOT);
    MAP_ERROR(ECANCELED); MAP_ERROR(EOWNERDEAD); MAP_ERROR(ENOTRECOVERABLE);
#undef MAP_ERROR
    case LKL_ENODATA: return ENOATTR;
    case LKL_EOPNOTSUPP: return ENOTSUP;
    case LKL_ENOMEDIUM: return ENXIO;
    case LKL_ENOKEY: case LKL_EKEYEXPIRED: case LKL_EKEYREVOKED:
    case LKL_EKEYREJECTED: return EACCES;
    default: return EIO;
    }
}

static inline long lkfs_host_result(long result)
{
    return result < 0 ? -lkfs_host_errno((int)-result) : result;
}

#endif
